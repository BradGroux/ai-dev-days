#!/usr/bin/env node

import { access, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const demoDir = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const reset = args.includes("--reset");
const outputFlag = args.indexOf("--output");
const requestedOutput = outputFlag >= 0 ? args[outputFlag + 1] : ".live-workspace";

if (!requestedOutput || requestedOutput.startsWith("--")) {
  throw new Error("--output requires a directory path.");
}

const outputDir = isAbsolute(requestedOutput)
  ? requestedOutput
  : resolve(demoDir, requestedOutput);
const marker = join(outputDir, ".houbas-generated-workspace");

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

if (await exists(outputDir)) {
  if (!reset) {
    throw new Error(
      `Live workspace already exists at ${outputDir}. Preserve it or rerun with --reset.`
    );
  }
  if (!(await exists(marker))) {
    throw new Error(`Refusing to reset an unmarked directory: ${outputDir}`);
  }
  await rm(outputDir, { recursive: true });
}

await mkdir(join(outputDir, "drafts"), { recursive: true });
await cp(join(demoDir, "starter/AGENTS.md"), join(outputDir, "AGENTS.md"));
await cp(join(demoDir, "starter/README.md"), join(outputDir, "README.md"));
await cp(
  join(demoDir, "starter/audience-decisions.md"),
  join(outputDir, "drafts/audience-decisions.md")
);
await cp(join(demoDir, "source"), join(outputDir, "source"), { recursive: true });
await cp(join(demoDir, "prompts"), join(outputDir, "prompts"), { recursive: true });
await cp(
  join(demoDir, "framework-guidance.md"),
  join(outputDir, "framework-guidance.md")
);
await writeFile(
  marker,
  "Generated by prepare-live-workspace.mjs. Use --reset only after preserving wanted drafts.\n"
);

const readme = await readFile(join(outputDir, "README.md"), "utf8");
if (!readme.includes("fictional")) {
  throw new Error("Prepared workspace lost its fictional-data safety marker.");
}

console.log(`Prepared fictional live workspace: ${outputDir}`);
console.log("Open that folder in Codex, then begin with prompts/01-audit-current-state.md.");
